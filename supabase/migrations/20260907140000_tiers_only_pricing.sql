-- ------------------------------------------------------------
--  1) تحويل الأسعار القائمة إلى شريحة واحدة مفتوحة الطرف
--
--  الشرط المزدوج يجعل التشغيل المتكرّر بلا أثر:
--  المنتج الذي نال شريحته لا يعود يطابق tiers = '[]'.
--
--  و max: null تعني «فما فوق» — وهي الصورة التي تقرؤها
--  tier_unit_price ويرسمها المتصفّح، فلا يبقى سقف يُسقط
--  الطلبات الكبيرة إلى السعر الأساسي.
-- ------------------------------------------------------------
update public.products
   set tiers = jsonb_build_array(
         jsonb_build_object(
           'min',   1,
           'max',   null,
           'price', round(price, 2)
         )
       )
 where coalesce(jsonb_array_length(tiers), 0) = 0
   and price is not null
   and price > 0;


-- ------------------------------------------------------------
--  2) تقرير: ماذا صار لكل منتج
--
--  محرّر الاستعلام يعرض نتيجة آخر جملة وحدها، فهذه هي
--  الجملة الأخيرة عمداً.
-- ------------------------------------------------------------
select id,
       name,
       price as base_price,
       jsonb_array_length(tiers) as tier_count,
       case
         when jsonb_array_length(tiers) = 0 then 'no price - shows on request'
         else 'ok'
       end as status
  from public.products
 order by id;
