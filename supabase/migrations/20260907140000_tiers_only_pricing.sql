--
--  وعمود price يبقى في القاعدة ولا يُحذف (بقرار المالك):
--   • الطلبات القديمة حُسبت به، وحذفه يفقد سندها.
--   • create_order_from_cart تستعمله آخرَ ملاذ، فبقاؤه شبكة
--     أمان لمنتج فقد شرائحه بخطأ — أهون من طلب بسعر صفر.
--   • والتراجع ممكن ما دام العمود قائماً.
--
--  التحويل أدناه يُنشئ لكل منتج بلا شرائح شريحةً واحدة
--  «من 1 فما فوق» بسعره الحالي، فلا يفقد منتج سعره.
--
--  طريقة التطبيق: Supabase ← SQL Editor ← New query ← لصق ← Run
--  الملف قابل لإعادة التشغيل بأمان.
