-- ------------------------------------------------------------
--  ١) تنظيف: حذف المتابعات التي تخالف القاعدة الجديدة
--
--  لا بدّ أن يسبق تشديد السياسة، وإلا بقيت صفوف قديمة تخالفها
--  — فالسياسة تحكم الإدراج الجديد ولا تمسّ ما مضى.
-- ------------------------------------------------------------
delete from public.factory_follows f
 using public.factories fa
 where fa.id = f.factory_id
   and fa.owner_id = f.user_id;


-- ------------------------------------------------------------
--  ٢) سياسة الإضافة: صفّي أنا، ولمصنع ليس لي
-- ------------------------------------------------------------
drop policy if exists factory_follows_insert on public.factory_follows;

create policy factory_follows_insert
  on public.factory_follows for insert
  with check (
    user_id = auth.uid()
    and not exists (
      select 1 from public.factories fa
       where fa.id = factory_id
         and fa.owner_id = auth.uid()
    )
  );


-- ============================================================
--  تحقّق: يجب أن يكون العدد صفراً — لا مالك يتابع مصنعه
-- ============================================================
select count(*) as self_follows
  from public.factory_follows f
  join public.factories fa on fa.id = f.factory_id
 where fa.owner_id = f.user_id;
