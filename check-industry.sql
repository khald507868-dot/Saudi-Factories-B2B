-- ============================================================
--  فحص: هل القطاع (industry) محفوظ لمصانعك؟
--
--  الخطوات:
--   Supabase → SQL Editor → New query → الصق هذا → Run
--
--  العمود industry يجب أن يحمل الاسم الإنجليزي للفئة،
--  مثل: Food & Beverages
--  لو ظهر فارغاً، فالقطاع لم يُحفظ بعد — افتح صفحة مصنعك
--  واختر القطاع من القائمة، ثم أعد هذا الفحص.
-- ============================================================

select
  id,
  name              as "اسم المصنع",
  status            as "الحالة",
  coalesce(nullif(industry, ''), '(فارغ — لم يُحفظ)') as "القطاع"
from public.factories
order by created_at desc;
