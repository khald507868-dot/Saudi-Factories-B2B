-- ------------------------------------------------------------
--  ١) استعراض ما سيُحذف — اقرأه قبل الحذف
--
--  شغّل هذا الجزء وحده أوّلاً إن أردت التأكّد من العدد والمبالغ.
-- ------------------------------------------------------------
select id, status, total, created_at
  from public.orders
 order by created_at desc;


-- ------------------------------------------------------------
--  ٢) الحذف
--
--  كل الطلبات، لأنّ القاعدة اليوم لا تحوي إلا طلبات الاختبار.
--
--  تحذير لمن يقرأ هذا الملف لاحقاً: بعد أن يبدأ البيع الحقيقي
--  لا يجوز تشغيل هذا الجزء إطلاقاً — عدّل الأمر ليحذف بمعرّف
--  محدّد:  delete from public.orders where id = '<uuid>';
-- ------------------------------------------------------------
delete from public.orders;


-- ============================================================
--  تحقّق: يجب أن يكون العدد صفراً
-- ============================================================
select count(*) as remaining_orders from public.orders;
