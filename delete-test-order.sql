--  لماذا من هنا لا من الموقع:
--  لا توجد سياسة delete على orders إطلاقاً، فالحذف من المتصفّح
--  مستحيل — وهذا مقصود: الطلب سجلّ مالي لا يُمحى بضغطة. أمّا في
--  محرّر SQL فأنت تعمل بصلاحية المالك مباشرة.
