-- ============================================================
-- حذف الطلب التجريبي 1379a397-e830-4d56-8750-a0af5ed40893
-- ------------------------------------------------------------
-- أُنشئ لاختبار إصلاح tier_unit_price بعد أن كان الشراء
-- معطّلاً، وليس طلباً حقيقيّاً من مشترٍ.
--
-- البنود ومحاولات الدفع تُحذف معه تلقائيّاً: كلاهما مرتبط
-- بـon delete cascade، فلا حاجة لحذفها يدويّاً.
--
-- الحذف بالمعرّف وحده لا بشرط عامّ مثل «آخر طلب» أو
-- «طلبات اليوم»: شرط عامّ في محرّر SQL يمسح ما لم يُقصد،
-- ولا تراجع بعده.
--
-- Supabase → SQL Editor → New query → لصق → Run
-- ============================================================

-- 1) ما الذي سيُحذف؟ ----------------------------------------
-- تُقرأ أوّلاً للتأكّد من أنّه الطلب المقصود.
select o.id,
       o.status,
       o.total,
       o.created_at,
       (select count(*) from public.order_items i where i.order_id = o.id) as items
  from public.orders o
 where o.id = '1379a397-e830-4d56-8750-a0af5ed40893';

-- 2) الحذف ---------------------------------------------------
delete from public.orders
 where id = '1379a397-e830-4d56-8750-a0af5ed40893';

-- 3) تحقّق: يجب أن يكون العدد صفراً --------------------------
-- محرّر Supabase يعرض نتيجة آخر استعلام وحده، فهذا ما تراه.
select count(*) as remaining
  from public.orders
 where id = '1379a397-e830-4d56-8750-a0af5ed40893';
